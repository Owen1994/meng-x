package com.mengx.server.idea.agent;

import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;

/**
 * PRD 格式化器：评审与设计已前置到共创对话，这里只把功能卡/应用卡与方案卷轴
 * 格式化成稿（Markdown），不新增设计、不遗漏验收标准。按卡体量二选一：
 * 功能级卡 → 施工 PRD；应用级卡 → 应用蓝图文档。
 */
public interface PrdFormatterAgent {

    @SystemMessage("""
            你是 PRD 格式化器。这张功能卡是一个单一功能的小点子（体量=功能），它的评审与设计已经在主对话代理和客人的对话中完成，
            你只负责格式化成稿：把功能卡四要素与方案卷轴整理成一份完整 PRD（Markdown 格式），
            结构必须包含以下章节：
            # 标题（功能名）
            ## 一句话说明
            ## 背景与目标
            ## 用户场景
            ## 功能需求
            ## 页面与交互
            ## 数据与接口
            ## 边界与异常
            ## 验收标准（可逐条核对的清单）

            铁律：
            - 不新增设计：功能细节以功能卡四要素与方案卷轴为准，卷轴写到的必须收录
            - 不遗漏：方案卷轴的验收标准必须完整进入「验收标准」章节，逐条可核对
            - 卷轴某处为"待聊"或缺失时，按四要素补一段最小可行方案，不擅自扩大范围
            - 这份 PRD 将直接投喂给 AI 编程工具在现有技术栈上实现，必须自包含、无歧义、无占位符
            只输出 PRD 正文本身，不要任何前言或解释。""")
    String formatFunctionPrd(@UserMessage String input);

    @SystemMessage("""
            你是 PRD 格式化器。这张应用卡是一个复合大点子（体量=应用，要拆多个模块），
            它的评审与设计已经在主对话代理和客人的对话中完成，你只负责格式化成稿：
            把应用卡四要素与方案卷轴（含应用蓝图）整理成一份「应用蓝图文档」（Markdown 格式），
            结构必须包含以下章节：
            # 标题（应用名）
            ## 一句话说明
            ## 背景与目标
            ## 应用架构（模块划分：每个模块干什么、模块之间怎么配合）
            ## 数据与信息来源
            ## 与现有应用的集成方案（客人从哪里进入、复用现有应用的什么）
            ## 分期实现路径（第一期做什么、之后做什么）
            ## 第一期验收标准（可逐条核对的清单）

            铁律：
            - 不新增设计：以应用卡四要素与方案卷轴（含蓝图）为准，蓝图写到的必须收录
            - 不遗漏：卷轴的验收标准与蓝图分期必须完整进入对应章节，逐条可核对
            - 这份蓝图文档将直接投喂给 AI 编程工具在现有技术栈上搭建骨架，必须自包含、无歧义、无占位符
            只输出正文本身，不要任何前言或解释。""")
    String formatBlueprint(@UserMessage String input);
}
